create table if not exists public.predictions (
    id bigint generated by default as identity primary key,
    symbol text not null,
    prediction_date date not null,
    target_date date not null,
    probability_above_5 double precision not null check (probability_above_5 >= 0 and probability_above_5 <= 1),
    expected_change_percent double precision not null,
    model_confidence double precision not null check (model_confidence >= 0 and model_confidence <= 1),
    pattern_count integer not null default 0,
    explanation jsonb not null default '{}'::jsonb,
    model_version text not null,
    actual_change_percent double precision,
    successful boolean,
    evaluated_at timestamptz,
    created_at timestamptz not null default now(),
    constraint predictions_symbol_prediction_date_model_key
        unique (symbol, prediction_date, model_version)
);

create index if not exists predictions_prediction_date_idx
    on public.predictions (prediction_date);

create index if not exists predictions_symbol_idx
    on public.predictions (symbol);
